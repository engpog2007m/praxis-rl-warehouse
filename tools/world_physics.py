#!/usr/bin/env python3
"""Classify or reverse the wheel-traction physics correction in a world SDF.

Background (docs/KNOWN_ISSUES.md, issue 1): the original AMR models had no
wheel friction and a chassis collision cylinder resting on the ground plane.
Under full commanded velocity the robot moved about 0.5 mm in 3 s while its
odometry reported normal travel. The correction below restored traction.

  check <world.sdf>    report whether the file is CORRECTED, LEGACY or UNKNOWN
  legacy <world.sdf>   write <name>_legacy_defect.sdf with the correction
                       reversed, so Era 1 numbers can be reproduced exactly.
                       The legacy world is physically invalid by design and
                       must not be used for new results.

The reversal is verified by re-applying the correction and confirming the
result is byte-identical to the input.
"""
import pathlib
import sys

WHEEL_LEGACY = (
    '        <collision name="c"><geometry><cylinder><radius>0.033</radius>'
    '<length>0.018</length></cylinder></geometry></collision>'
)
WHEEL_FIXED = (
    '        <collision name="c"><geometry><cylinder><radius>0.033</radius>'
    '<length>0.018</length></cylinder></geometry>\n'
    '          <surface>\n'
    '            <friction><ode><mu>1.2</mu><mu2>1.2</mu2>\n'
    '              <fdir1>0 0 1</fdir1><slip1>0.0</slip1><slip2>0.0</slip2>\n'
    '            </ode></friction>\n'
    '            <contact><ode><kp>1e6</kp><kd>100</kd></ode></contact>\n'
    '          </surface>\n'
    '        </collision>'
)
MASS_LEGACY = (
    '<inertial><mass>0.01</mass><inertia><ixx>0.001</ixx><ixy>0</ixy><ixz>0</ixz>'
    '<iyy>0.001</iyy><iyz>0</iyz><izz>0.001</izz></inertia></inertial>'
)
MASS_FIXED = (
    '<inertial><mass>0.05</mass><inertia><ixx>1.5e-5</ixx><ixy>0</ixy><ixz>0</ixz>'
    '<iyy>1.5e-5</iyy><iyz>0</iyz><izz>2.7e-5</izz></inertia></inertial>'
)
BASE_LEGACY = (
    '        <collision name="base_collision">\n'
    '          <geometry><cylinder><radius>0.105</radius><length>0.143</length>'
    '</cylinder></geometry>\n'
    '        </collision>'
)
BASE_FIXED = (
    '        <collision name="base_collision">\n'
    '          <pose>0 0 0.05 0 0 0</pose>\n'
    '          <geometry><cylinder><radius>0.105</radius><length>0.09</length>'
    '</cylinder></geometry>\n'
    '          <surface><friction><ode><mu>0.05</mu><mu2>0.05</mu2></ode>'
    '</friction></surface>\n'
    '        </collision>'
)
PAIRS = [('wheel', WHEEL_LEGACY, WHEEL_FIXED),
         ('mass', MASS_LEGACY, MASS_FIXED),
         ('base', BASE_LEGACY, BASE_FIXED)]


def classify(text):
    fixed = {k: text.count(f) for k, _, f in PAIRS}
    legacy = {k: text.count(l) for k, l, _ in PAIRS}
    if fixed['wheel'] and fixed['base'] and not legacy['wheel'] and not legacy['base']:
        return 'CORRECTED', fixed, legacy
    if legacy['wheel'] and legacy['base'] and not fixed['wheel'] and not fixed['base']:
        return 'LEGACY', fixed, legacy
    return 'UNKNOWN', fixed, legacy


def to_legacy(text):
    for _, legacy, fixed in PAIRS:
        text = text.replace(fixed, legacy)
    return text


def to_fixed(text):
    for _, legacy, fixed in PAIRS:
        text = text.replace(legacy, fixed)
    return text


def main(argv):
    if len(argv) != 3 or argv[1] not in ('check', 'legacy'):
        print(__doc__)
        return 2
    path = pathlib.Path(argv[2])
    text = path.read_text(encoding='utf-8')
    state, fixed, legacy = classify(text)

    if argv[1] == 'check':
        print(f'{path.name}: {state}  (corrected blocks {fixed}, legacy blocks {legacy})')
        return 0 if state == 'CORRECTED' else 1

    if state != 'CORRECTED':
        print(f'{path.name} is {state}, not CORRECTED; refusing to reverse. '
              f'corrected={fixed} legacy={legacy}')
        return 1
    out_text = to_legacy(text)
    if to_fixed(out_text) != text:
        print('Round-trip verification failed; no file written.')
        return 1
    out = path.with_name(path.stem + '_legacy_defect.sdf')
    header = ('<!-- GENERATED by tools/world_physics.py. PHYSICALLY INVALID BY '
              'DESIGN: reproduces the wheel-traction defect for Era 1 '
              'replication only. Do not use for new results. -->\n')
    body = out_text
    if body.startswith('<?xml'):
        first, rest = body.split('\n', 1)
        body = first + '\n' + header + rest
    else:
        body = header + body
    out.write_text(body, encoding='utf-8')
    print(f'wrote {out}  (round-trip verified; reversed {fixed})')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
